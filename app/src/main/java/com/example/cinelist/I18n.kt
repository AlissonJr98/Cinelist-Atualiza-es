    /**
     * Traduz uma string em português para o idioma ativo.
     * Caso não haja tradução ou o idioma ativo seja português, retorna o texto original.
     */
    fun traduzir(textoPt: String): String {
        val lang = idiomaAtivo.lowercase().take(2)
        if (lang == "pt") return textoPt
        return dicionario[lang]?.get(textoPt) ?: textoPt
    }
